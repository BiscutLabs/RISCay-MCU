import hashlib
import json
import unittest
import tempfile
from pathlib import Path

from sram_assets import ROOT, verify
from sram_assets import validate_export


class SramAssetsTest(unittest.TestCase):
    def test_vendored_models_match_pinned_upstream_bytes(self):
        lock = json.loads((ROOT / "soc/sram-lock.json").read_text())
        for suffix in (".v", ".blackbox.v"):
            name = lock["macro"] + suffix
            verify((ROOT / "soc/src/main/resources/riscay/sram" / name).read_bytes(),
                   lock["assets"][name]["sha256"])

    def test_corrupt_physical_view_is_rejected(self):
        digest = hashlib.sha256(b"physical view").hexdigest()
        verify(b"physical view", digest)
        with self.assertRaisesRegex(ValueError, "SRAM_ASSET_HASH_MISMATCH"):
            verify(b"changed physical view", digest)

    def test_emitted_fixed_view_retains_unknown_memory_contents(self):
        lock=json.loads((ROOT/'soc/sram-lock.json').read_text());model=lock['macro']
        source=ROOT/'soc/src/main/resources/riscay/sram'
        body='`ifdef SYNTHESIS\n'+(source/(model+'.blackbox.v')).read_text()+'\n`else\n'+(source/(model+'.v')).read_text().replace("mem[i] = 8'd0;", "mem[i] = 8'bx;")+'\n`endif\n\n'
        with tempfile.TemporaryDirectory() as directory:
            path=Path(directory)/(model+'.sv')
            path.write_text('// Generated by CIRCT firtool-test\n'+body)
            validate_export(directory,'test')
            path.write_text('// Generated by CIRCT firtool-test\n'+body.replace("mem[i] = 8'bx;", "mem[i] = 8'd0;"))
            with self.assertRaisesRegex(ValueError,'SRAM_EMITTED_VIEW_MISMATCH'):validate_export(directory,'test')


if __name__=='__main__':unittest.main()
